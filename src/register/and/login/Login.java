    private void jButtonLoginActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButtonLoginActionPerformed
        String username = jTextFieldUsername.getText().trim();
        char[] passwordChars = jPasswordField.getPassword();
        String password = new String(passwordChars);
        
        // Clear the password array for security
        java.util.Arrays.fill(passwordChars, '0');
        
        // Validate that fields aren't empty
        if (username.isEmpty() || password.isEmpty()) {
            JOptionPane.showMessageDialog(this, 
                "Please enter both username and password", 
                "Login Error", 
                JOptionPane.ERROR_MESSAGE);
            return;
        }
        
        boolean loginSuccessful = loginUser(username, password);
        String loginMessage = returnLoginStatus(loginSuccessful, username);
        
        JOptionPane.showMessageDialog(this, 
            loginMessage, 
            loginSuccessful ? "Login Successful" : "Login Failed",
            loginSuccessful ? JOptionPane.INFORMATION_MESSAGE : JOptionPane.ERROR_MESSAGE);
        
        if (!loginSuccessful) {
            jPasswordField.setText("");
        }
    }//GEN-LAST:event_jButtonLoginActionPerformed

    
