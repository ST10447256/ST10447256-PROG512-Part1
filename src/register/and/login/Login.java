    // Check username format
    public boolean checkUserName(String username) {
        return username.contains("_") && username.length() <= 5;
    }
    
    // Check password complexity
    public boolean checkPasswordComplexity(String password) {
        String regex = "^(?=.*[0-9])(?=.*[a-z])(?=.*[A-Z])(?=.*[@#$%^&+=!])(?=\\S+$).{8,}$";
        Pattern pattern = Pattern.compile(regex);
        Matcher matcher = pattern.matcher(password);
        return matcher.matches();
    }
    
    // Check cell phone format
    public boolean checkCellPhoneNumber(String cellNumber) {
        // South African numbers start with +27 followed by 9 digits
        return cellNumber != null && cellNumber.startsWith("+27") && cellNumber.length() == 12;
    }
    
    // Register user with validation
    public String registerUser(String username, String password, String cellNumber) {
        boolean usernameValid = checkUserName(username);
        boolean passwordValid = checkPasswordComplexity(password);
        boolean cellValid = checkCellPhoneNumber(cellNumber);
        
        if (!usernameValid) {
            return "Username is not correctly formatted, please ensure that your username contains an underscore and is no more than five characters in length.";
        }
        if (!passwordValid) {
            return "Password is not correctly formatted, please ensure that the password contains at least eight characters, a capital letter, a number, and a special character.";
        }
        if (!cellValid) {
            return "Cell phone number is incorrectly formatted or does not contain an international code, please correct the number and try again.";
        }
        
        // If all valid, store the details
        this.registeredUsername = username;
        this.registeredPassword = password;
        this.registeredCellNumber = cellNumber;
        
        return "User registered successfully!";
    }
    
    // Login validation
    public boolean loginUser(String username, String password) {
        return username.equals(registeredUsername) && password.equals(registeredPassword);
    }
    
    // Return login status message
    public String returnLoginStatus(boolean loginStatus, String username) {
        if (loginStatus) {
            String[] nameParts = username.split("_");
            String firstName = nameParts.length > 0 ? nameParts[0] : username;
            String lastName = nameParts.length > 1 ? nameParts[1] : "";
            return "Welcome " + firstName + ", " + lastName + " it is great to see you again.";
        } else {
            return "Username or password incorrect, please try again.";
        }
    }

